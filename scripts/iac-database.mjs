// `pnpm iac:database`: creates the application's database roles and the
// database `app` on the managed PostgreSQL that infra/terraform/digitalocean
// provisioned (docs/deploy-vps.md#provision-with-terraform-digitalocean), by
// running infra/terraform/digitalocean/database/roles.sql on the server, the
// only machine the database accepts. Run it from the repository root, with
// the Terraform workspace of the environment selected, once cloud-init has
// finished on the server. Safe to run again: it then only sets the two
// passwords to Terraform's (after a rotation).
//
// What it sends where:
//   - the outputs of `terraform output -json` (the state, local or remote);
//   - over SSH, as the administrator of the server, to a throwaway container
//     of the pinned PostgreSQL image (scripts/tool-images/Dockerfile) that runs
//     psql: doadmin's password on the first line of standard input, then the
//     script. Nothing secret is on a command line or written to a file;
//   - the roles' passwords as SCRAM-SHA-256 verifiers, computed here, so the
//     server, its logs and psql never see them in clear.
import { createHash, createHmac, pbkdf2Sync, randomBytes } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { toolImage } from './tool-image.mjs';

const MODULE = fileURLToPath(new URL('../infra/terraform/digitalocean', import.meta.url));
const ROLES_SQL = new URL('../infra/terraform/digitalocean/database/roles.sql', import.meta.url);

/** PostgreSQL's default (scram_iterations): what `ALTER ROLE ... PASSWORD` would use. */
const SCRAM_ITERATIONS = 4096;

/**
 * The SCRAM-SHA-256 verifier PostgreSQL stores for `password` (RFC 5802 and
 * RFC 7677, in PostgreSQL's format). Given in `ALTER ROLE ... PASSWORD`, it is
 * stored as it is: the password itself never reaches the server.
 * @param {string} password ASCII, as generated by database.tf (SASLprep is the identity there)
 * @param {{ salt?: Buffer; iterations?: number }} [options]
 */
export function scramSha256Verifier(
  password,
  { salt = randomBytes(16), iterations = SCRAM_ITERATIONS } = {},
) {
  if (!/^[\x21-\x7e]+$/.test(password)) {
    throw new Error('The password must be printable ASCII without spaces.');
  }
  const salted = pbkdf2Sync(password, salt, iterations, 32, 'sha256');
  const clientKey = createHmac('sha256', salted).update('Client Key').digest();
  const storedKey = createHash('sha256').update(clientKey).digest();
  const serverKey = createHmac('sha256', salted).update('Server Key').digest();
  return `SCRAM-SHA-256$${iterations}:${salt.toString('base64')}$${storedKey.toString('base64')}:${serverKey.toString('base64')}`;
}

/**
 * The psql input that applies roles.sql: the two verifiers as the variables
 * the script reads, then the script.
 * @param {{ migratorPassword: string; runtimePassword: string; sql?: string }} input
 */
export function rolesScript({
  migratorPassword,
  runtimePassword,
  sql = readFileSync(ROLES_SQL, 'utf8'),
}) {
  // Base64, digits, $ and : only: nothing to escape inside psql's quotes.
  return [
    `\\set migrator_password '${scramSha256Verifier(migratorPassword)}'`,
    `\\set runtime_password '${scramSha256Verifier(runtimePassword)}'`,
    sql,
  ].join('\n');
}

/**
 * The connection details of the outputs, checked: every value that goes into
 * the remote command line is plain (host names, numbers, identifiers).
 * @param {Record<string, { value: unknown }>} outputs `terraform output -json`
 */
export function connection(outputs) {
  /** @param {string} name */
  const value = (name) => {
    const entry = outputs[name];
    if (typeof entry?.value !== 'string' || entry.value.length === 0) {
      throw new Error(
        `No output "${name}": run \`terraform apply\` first, in the workspace of this environment.`,
      );
    }
    return entry.value;
  };
  const admin = new URL(value('database_admin_url'));
  const ssh = value('ssh_admin');
  const settings = {
    ssh,
    host: admin.hostname,
    port: admin.port || '5432',
    user: decodeURIComponent(admin.username),
    database: admin.pathname.replace(/^\//, ''),
    adminPassword: decodeURIComponent(admin.password),
    migratorPassword: decodeURIComponent(new URL(value('database_migrator_url')).password),
    runtimePassword: decodeURIComponent(new URL(value('database_runtime_url')).password),
  };
  const plain = {
    ssh: /^[a-z_][a-z0-9_-]*@[0-9.]+$/,
    host: /^[a-z0-9.-]+$/,
    port: /^[0-9]{1,5}$/,
    user: /^[a-z_][a-z0-9_]*$/,
    database: /^[a-z_][a-z0-9_]*$/,
  };
  for (const [key, pattern] of Object.entries(plain)) {
    const field = /** @type {keyof typeof plain} */ (key);
    if (!pattern.test(settings[field])) {
      throw new Error(`Unexpected ${key} in the Terraform outputs: ${settings[field]}`);
    }
  }
  for (const key of /** @type {const} */ ([
    'adminPassword',
    'migratorPassword',
    'runtimePassword',
  ])) {
    if (settings[key].length === 0 || /[\r\n]/.test(settings[key])) {
      throw new Error(`The ${key} of the Terraform outputs is empty or spans lines.`);
    }
  }
  return settings;
}

/**
 * The command the server runs: psql in the pinned image, the connection from
 * the environment, the password read from the first line of standard input.
 * @param {ReturnType<typeof connection>} settings
 * @param {string} image
 */
export function remoteCommand(settings, image) {
  const env = {
    PGHOST: settings.host,
    PGPORT: settings.port,
    PGUSER: settings.user,
    PGDATABASE: settings.database,
    PGSSLMODE: 'require',
  };
  return [
    'sudo docker run --rm -i',
    ...Object.entries(env).map(([key, value]) => `-e ${key}=${value}`),
    image,
    `sh -c 'IFS= read -r PGPASSWORD && export PGPASSWORD && exec psql -X -q -v ON_ERROR_STOP=1'`,
  ].join(' ');
}

const isCli = import.meta.url === pathToFileURL(process.argv[1] ?? '').href;
if (isCli) {
  const output = spawnSync('terraform', [`-chdir=${MODULE}`, 'output', '-json'], {
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'inherit'],
    maxBuffer: 16 * 1024 * 1024,
  });
  if (output.error || output.status !== 0) {
    console.error(
      `terraform output failed${output.error ? ` (${output.error.message})` : ''}: run it from the repository root, with Terraform installed and the state of this environment reachable.`,
    );
    process.exit(1);
  }
  const workspace = spawnSync('terraform', [`-chdir=${MODULE}`, 'workspace', 'show'], {
    encoding: 'utf8',
  }).stdout.trim();
  const settings = connection(JSON.parse(output.stdout));
  console.log(
    `Applying database/roles.sql (workspace ${workspace}) through ${settings.ssh} to ${settings.host}...`,
  );
  const run = spawnSync(
    'ssh',
    ['-T', settings.ssh, remoteCommand(settings, toolImage('postgres'))],
    {
      input: `${settings.adminPassword}\n${rolesScript(settings)}`,
      stdio: ['pipe', 'inherit', 'inherit'],
    },
  );
  if (run.error || run.status !== 0) {
    console.error(
      `The roles were not applied${run.error ? ` (${run.error.message})` : ''}. Check that cloud-init has finished on the server (ssh ${settings.ssh} cloud-init status --wait) and see docs/deploy-vps.md#provision-with-terraform-digitalocean.`,
    );
    process.exit(1);
  }
  console.log(
    'Done: the database app (owner app_migrator) and the role app_runtime. Their connection strings: terraform output -raw database_migrator_url / database_runtime_url.',
  );
}
