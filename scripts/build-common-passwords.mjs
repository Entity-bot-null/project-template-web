// The policy's bounds (password-policy.ts): shorter ones are refused anyway.
const MIN_LENGTH = 15;
const MAX_LENGTH = 200;
const OUTPUT = fileURLToPath(new URL('../apps/api/src/auth/common-passwords.ts', import.meta.url));

/**
 * How the policy compares: NFKC, lowercase (password-policy.ts).
 * @param {string} password
 */
export function comparable(password) {
  return password.normalize('NFKC').toLowerCase();
}

/**
 * The entries to keep from the source lines: comparable, within the
 * policy's length, printable, unique, sorted.
 * @param {Iterable<string>} lines
 */
export function selectEntries(lines) {
  const entries = new Set();
  for (const line of lines) {
    const entry = comparable(line);
    const length = [...entry].length;
    // Control characters are not something a person types.
    if (length < MIN_LENGTH || length > MAX_LENGTH || /\p{Cc}/u.test(entry)) continue;
    entries.add(entry);
  }
  return [...entries].sort();
}

/**
 * The lines of one source file, after its checksum matched.
 * @param {{ file: string; sha256: string }} source
 */
async function download({ file, sha256 }) {
  const url = `https://raw.githubusercontent.com/danielmiessler/SecLists/${COMMIT}/Passwords/Common-Credentials/${file}`;
  const response = await fetch(url, { redirect: 'error' });
  if (!response.ok) throw new Error(`${file}: HTTP ${String(response.status)}`);
  const bytes = Buffer.from(await response.arrayBuffer());
  const actual = createHash('sha256').update(bytes).digest('hex');
  if (actual !== sha256) throw new Error(`${file}: SHA-256 ${actual}, expected ${sha256}`);
  return bytes.toString('utf8').split(/\r?\n/);
}

async function main() {
  const lines = (await Promise.all(SOURCES.map(download))).flat();
  const entries = selectEntries(lines);
  writeFileSync(
    OUTPUT,
    `// GENERATED by scripts/build-common-passwords.mjs: do not edit by hand.
//
// ${String(entries.length)} passwords of ${String(MIN_LENGTH)} characters or more among the most used ones,
// NFKC-normalized and lowercased, one per line: the union of
// ${SOURCES.map(({ file }) => file).join(', ')}
// from SecLists (https://github.com/danielmiessler/SecLists), commit
// ${COMMIT}.
// SecLists' license, as it requires:
//
${SECLISTS_LICENSE.split('\n')
  .map((line) => (line ? `// ${line}` : '//'))
  .join('\n')}
export const COMMON_PASSWORD_LIST = ${JSON.stringify(entries.join('\n'))};
`,
  );
  console.log(`Wrote ${String(entries.length)} entries to ${OUTPUT}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
