// or more that people use most, which the password policy refuses
// (apps/api/src/auth/password-policy.ts, docs/security.md#passwords). Checked
// locally: a password never leaves the API to be looked up.
//
//   node scripts/build-common-passwords.mjs
//
// Source: SecLists (MIT), Passwords/Common-Credentials, at a pinned commit;
// each file is verified against its SHA-256 before use, so a moved file or a
// tampered download stops the build instead of changing the list. To update,
// pin a newer commit and its checksums, run this, and review the diff.
